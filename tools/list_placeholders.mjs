// Lists every placeholder picture by name, size and where it's used, so each can be redrawn
// and dropped into public/swap (see public/swap/README.md).
//   node tools/list_placeholders.mjs            prints a table
//   node tools/list_placeholders.mjs --md       writes docs/PLACEHOLDERS.md
//   node tools/list_placeholders.mjs --json     prints JSON
// Needs playwright (PW=/path/to/playwright if it isn't on the module path).
import { createServer } from 'vite';
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const { chromium } = createRequire(import.meta.url)(process.env.PW || 'playwright');
const swapped = (dir) => (existsSync(`public/swap/${dir}`) ? readdirSync(`public/swap/${dir}`).map((f) => f.replace(/\.png$/, '')) : []);
const swappedPieces = existsSync('public/swap/pieces') ? readdirSync('public/swap/pieces', { withFileTypes: true }).filter((e) => e.isDirectory()).flatMap((d) => readdirSync(`public/swap/pieces/${d.name}`).map((f) => `${d.name}/${f.replace(/\.png$/, '')}`)) : [];

// where things are used: island maps (t:name, p:id refs) and the code
const maps = readdirSync('src/maps').filter((f) => f.endsWith('.json')).map((f) => [f, readFileSync(`src/maps/${f}`, 'utf8')]);
const countIn = (needle) => maps.filter(([, t]) => t.includes(needle)).map(([f]) => f.replace('.json', ''));
const code = readdirSync('src').filter((f) => f.endsWith('.js')).map((f) => readFileSync(`src/${f}`, 'utf8')).join('\n');
const rooms = readFileSync('src/rooms.js', 'utf8') + readFileSync('src/RoomScene.js', 'utf8');

const server = await createServer({ server: { port: 5199, strictPort: false }, logLevel: 'error' });
await server.listen();
const url = server.resolvedUrls.local[0];
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(`${url}tiles.html`);
await page.waitForTimeout(1500);
const tiles = await page.evaluate(async () => {
  const { buildTiles } = await import('/src/tiles.js');
  return Object.entries(buildTiles()).filter(([n]) => !n.includes('@')).map(([name, t]) => ({ name, label: t.label || name, group: t.group, w: t.frames[0].width, h: t.frames[0].height, frames: t.frames.length, walk: t.walk }));
});
const pieces = await (await page.request.get(`${url}builder/pieces.json`)).json();
await browser.close();
await server.close();

const out = [];
const doneTiles = swapped('tiles');
for (const t of tiles) {
  const onMaps = countIn(`"t:${t.name}"`).concat(countIn(`'${t.name}'`).filter((m) => !countIn(`"t:${t.name}"`).includes(m)));
  const inCode = new RegExp(`['"\`]${t.name}['"\`]`).test(code);
  out.push({ kind: 'tile', name: t.name, size: `${t.w}x${t.h}${t.frames > 1 ? ` x${t.frames} frames` : ''}`, what: `${t.group} / ${t.label}`, use: [...new Set(onMaps)].join(', ') || (inCode ? 'code' : 'palette only'), done: doneTiles.includes(t.name) });
}
const sizes = {};
for (const f of readdirSync('public/sprites/lpc')) {
  const b = readFileSync(`public/sprites/lpc/${f}`);
  sizes[f.replace('.png', '')] = `${b.readUInt32BE(16)}x${b.readUInt32BE(20)}`;
}
const doneSprites = swapped('sprites');
for (const [name, size] of Object.entries(sizes)) out.push({ kind: 'sprite', name, size, what: 'room furniture', use: new RegExp(`['"\`]${name.replace(/_\d$/, '')}`).test(rooms) ? 'rooms' : 'unused', done: doneSprites.includes(name) });
for (const g of pieces.groups)
  for (const p of g.pieces) out.push({ kind: 'piece', name: p.id, size: `${p.w}x${p.h}`, what: `${g.name || g.sheet} (${p.pack})`, use: countIn(`"p:${p.id}"`).join(', ') || 'palette only', done: swappedPieces.includes(p.id) });

if (process.argv.includes('--json')) console.log(JSON.stringify(out, null, 1));
else if (process.argv.includes('--md')) {
  const by = (k) => out.filter((o) => o.kind === k);
  const sec = (title, k, note) => `## ${title} (${by(k).length}, ${by(k).filter((o) => o.done).length} swapped)\n${note}\n\n| Name | Size | What | Used on | Swapped |\n|---|---|---|---|---|\n${by(k).map((o) => `| \`${o.name}\` | ${o.size} | ${o.what} | ${o.use} | ${o.done ? 'yes' : ''} |`).join('\n')}\n`;
  writeFileSync('docs/PLACEHOLDERS.md', `# Placeholder pictures\n\nGenerated by \`node tools/list_placeholders.mjs --md\`. Redraw one, name the PNG exactly as below and drop it in \`public/swap/\` (see public/swap/README.md). Every picture here is a placeholder.\n\n${sec('Island tiles and props', 'tile', 'Drawn in code. Folder `public/swap/tiles/<name>.png`; animated tiles have their frames side by side.')}\n${sec('Room furniture', 'sprite', 'Folder `public/swap/sprites/<name>.png`, any size.')}\n${sec('Builder pieces', 'piece', 'Folder `public/swap/pieces/<group>/<n>.png`, exactly the size shown.')}`);
  console.log(`wrote docs/PLACEHOLDERS.md: ${out.length} placeholders`);
} else out.forEach((o) => console.log(`${o.kind.padEnd(6)} ${o.name.padEnd(28)} ${o.size.padEnd(16)} ${o.use}${o.done ? '  [swapped]' : ''}`));
