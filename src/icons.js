export function iconSvg(name) {
  const rows = ICONS[name] || ICONS.look;
  const rects = [];
  rows.forEach((r, y) => [...r].forEach((c, x) => c === '#' && rects.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`)));
  return `<svg viewBox="0 0 11 11" width="18" height="18" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects.join('')}</svg>`;
}
